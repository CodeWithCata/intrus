/**
 * Builds the Netlify `_headers` file for the static build. A plain file in static/ could not work: the Content-Security-Policy
 * must allow the game server's address, which is only known at build time (VITE_PARTY_HOST).
 * Used by `node scripts/headers.mjs` after `pnpm build` (see netlify.toml). Set CSP_REPORT_ONLY=1 on a first deploy to
 * log violations in the browser console without blocking anything.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** "https://party.example.dev/" -> "party.example.dev". Anything that is not a plain host[:port] gives null. */
export function cleanHost(raw) {
  const host = String(raw ?? "").trim().replace(/^[a-z]+:\/\//i, "").replace(/\/+$/, "");
  return /^[a-z0-9]([a-z0-9.-]*[a-z0-9])?(:\d{1,5})?$/i.test(host) ? host : null;
}

export function buildCsp(partyHost) {
  const host = cleanHost(partyHost);
  const connect = ["'self'", ...(host ? [`wss://${host}`, `https://${host}`] : [])];
  return [
    "default-src 'self'",
    // SvelteKit's static pages start with an inline script, and Svelte sets inline styles, so both need 'unsafe-inline'.
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    // data: because app.html inlines the splash font (AntonSplash) as a base64 data URI.
    "font-src 'self' data:",
    "media-src 'self' blob: data:",
    `connect-src ${connect.join(" ")}`,
    "manifest-src 'self'",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'"
  ].join("; ");
}

/** @param {{ partyHost?: string | null, reportOnly?: boolean }} [options] */
export function buildHeaders({ partyHost, reportOnly = false } = {}) {
  const cspName = reportOnly ? "Content-Security-Policy-Report-Only" : "Content-Security-Policy";
  const noCache = "  Cache-Control: no-cache";
  return `# Generated by scripts/headers.mjs. Do not edit.
/*
  ${cspName}: ${buildCsp(partyHost)}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()

# Hashed build files never change: cache for a year.
/_app/immutable/*
  Cache-Control: public, max-age=31536000, immutable

# These must always be revalidated, or an installed app never sees an update.
/
${noCache}
/index.html
${noCache}
/service-worker.js
${noCache}
/manifest.json
${noCache}
/online/*
${noCache}
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const out = resolve(dirname(fileURLToPath(import.meta.url)), "..", process.argv[2] ?? "build", "_headers");
  const partyHost = process.env.VITE_PARTY_HOST;
  if (partyHost && !cleanHost(partyHost)) {
    console.error(`VITE_PARTY_HOST "${partyHost}" is not a plain host (like party.example.dev). Aborting.`);
    process.exit(1);
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, buildHeaders({ partyHost, reportOnly: process.env.CSP_REPORT_ONLY === "1" }));
  console.log(`wrote ${out} (online play ${cleanHost(partyHost) ? "allowed to " + cleanHost(partyHost) : "off"})`);
}
